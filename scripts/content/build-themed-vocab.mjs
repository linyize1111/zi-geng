function cardFromTuple(row) {
  const [term, zhuyin, pos, diff, cat, short, long, usage, daily, lit, ...tags] = row;
  return {
    status: "active",
    term,
    zhuyin,
    part_of_speech: pos,
    difficulty: diff,
    short_def: short,
    long_def: long,
    usage_context: usage,
    register: "literary",
    category: cat,
    tags: Array.from(new Set(["主題詞庫", "寫作者詞庫", "大學生以上", ...tags])),
    daily_example: daily.replace(/他攥著 priorit… /, ""),
    literary_example: lit,
    source: { kind: "zi-geng-themed-lexicon", version: 1, level: "college-to-pro" },
  };
}

const cards = [];
const seen = new Set();
for (const row of T) {
  const c = cardFromTuple(row);
  if (seen.has(c.term)) continue;
  seen.add(c.term);
  c.daily_example = String(c.daily_example).replace(/\s+/g, " ").trim();
  cards.push(c);
}

const byCat = {};
for (const c of cards) {
  const k = c.category.split("・")[0];
  byCat[k] = (byCat[k] ?? 0) + 1;
}

const payload = {
  version: 1,
  count: cards.length,
  themes: byCat,
  cards,
};

writeFileSync(join(__dir, "seed-themed-vocab.json"), JSON.stringify(payload, null, 2), "utf8");
const pub = join(__dir, "../../public/content");
mkdirSync(pub, { recursive: true });
writeFileSync(join(pub, "seed-themed-vocab.json"), JSON.stringify(payload), "utf8");
